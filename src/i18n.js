const DICTS = { ru, en };

export function readLanguage() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "en" || saved === "ru") return saved;
  } catch {
    /* private mode */
  }
  return "ru";
}

export function applyLanguage(lang) {
  if (typeof document !== "undefined") document.documentElement.lang = lang === "en" ? "en" : "ru";
}

function lookup(lang, key) {
  const parts = String(key).split(".");
  let node = DICTS[lang] || DICTS.ru;
  for (const part of parts) {
    if (node == null || typeof node !== "object") return undefined;
    node = node[part];
  }
  return node;
}

function fill(template, vars) {
  return String(template).replace(/\{(\w+)\}/g, (_, name) => (vars && vars[name] != null ? String(vars[name]) : ""));
}

export function pluralForm(lang, n, key) {
  const forms = lookup(lang, key) || lookup("ru", key);
  if (!forms || typeof forms === "string") return forms || "";
  if (lang === "en") return Math.abs(Number(n)) === 1 ? forms.one : forms.many;
  return ruPlural(n, forms.one, forms.few, forms.many);
}

export function translate(lang, key, vars) {
  const value = lookup(lang, key);
  const fallback = value == null ? lookup("ru", key) : value;
  if (typeof fallback !== "string") return key;
  return fill(fallback, vars);
}

export function makeT(lang) {
  const safe = lang === "en" ? "en" : "ru";
  const t = (key, vars) => translate(safe, key, vars);
  t.plural = (n, key) => pluralForm(safe, n, key);
  t.lang = safe;
  t.locale = safe === "en" ? "en-US" : "ru-RU";
  return t;
}

export function explain(error, t) {
  const code = error instanceof Error ? error.message : String(error || "");
  const text = t(`errors.${code}`);
  if (text !== `errors.${code}`) return text;
  return code || t("errors.generic");
}
